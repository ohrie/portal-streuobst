#!/usr/bin/env python3
"""Maintain the OSM mapping history shown on the statistics page.

The history is a list of one point per day: the number and area of all mapped
orchards plus the landuse=meadow + meadow=meadow_orchard areas - the same
figures as "Wiesen gesamt" on the statistics page. When the pipeline ran
several times a day, the last run of that day wins.

The pipeline calls update_history() after every run, which appends the current
figures to stats_history.json. Only the very first time, when that file does
not exist yet, the history is bootstrapped from the old stats.csv. Its column
layout changed three times (trees, fruit trees and orchard=plantation were
added later), so old rows are read by width:

     9 columns: date, orchards (count, ha), orchard_meadow (count, ha),
                streuobstwiesen (count, ha), trees, total_area_ha
    10 columns: like 9, plus fruit_trees before total_area_ha
    12 columns: like 10, plus orchard_plantation (count, ha) after orchard_meadow

Usage (re-create the file from the CSV, e.g. for the one-time bootstrap):
    python build_stats_history.py PATH/TO/stats.csv [--out PATH]
"""

import argparse
import csv
import json
import logging
import sys
from pathlib import Path

logger = logging.getLogger(__name__)

# Index of the meadow_orchard (landuse=meadow) count per row width. Orchard
# count is always column 1 and the combined area always the last column.
MEADOW_COUNT_INDEX = {9: 5, 10: 5, 12: 7}

NOTE = (
    "Generated by data-processing/build_stats_history.py - mapped orchards and "
    "orchard meadows in OpenStreetMap per day."
)


def history_from_csv(csv_path: Path) -> list[dict]:
    per_day: dict[str, dict] = {}
    with open(csv_path, newline="") as f:
        for row in csv.reader(f):
            if row[0] == "date":
                continue
            if len(row) not in MEADOW_COUNT_INDEX:
                logger.warning(f"Skipping CSV row of unexpected width {len(row)}: {row[:1]}")
                continue
            day = row[0][:10]
            per_day[day] = {
                "date": day,
                "count": int(row[1]) + int(row[MEADOW_COUNT_INDEX[len(row)]]),
                "area_ha": round(float(row[-1])),
            }
    return [per_day[day] for day in sorted(per_day)]


def point_from_stats(stats: dict) -> dict:
    """The current run as a history point (same fields as the CSV rows)."""
    return {
        "date": stats["generated"][:10],
        "count": stats.get("orchards_count", 0) + stats.get("streuobstwiesen_count", 0),
        "area_ha": round(
            stats.get("orchards_area_ha", 0) + stats.get("streuobstwiesen_area_ha", 0)
        ),
    }


def write_history(history: list[dict], out_file: Path) -> None:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    payload = {"note": NOTE, "history": history}
    out_file.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")


def update_history(stats: dict, history_file: Path, csv_file: Path) -> list[dict]:
    """Append the current run to history_file and return the full history."""
    if history_file.exists():
        history = json.loads(history_file.read_text())["history"]
    elif csv_file.exists():
        history = history_from_csv(csv_file)
        logger.info(f"   Bootstrapped {len(history)} history days from {csv_file}")
    else:
        history = []

    per_day = {p["date"]: p for p in history}
    point = point_from_stats(stats)
    per_day[point["date"]] = point
    history = [per_day[day] for day in sorted(per_day)]

    write_history(history, history_file)
    return history


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path, help="stats.csv from the pipeline output")
    parser.add_argument(
        "--out",
        type=Path,
        default=repo_root / "web/public/stats_history.json",
        help="output JSON path",
    )
    args = parser.parse_args()

    history = history_from_csv(args.csv)
    if not history:
        print("No usable rows found", file=sys.stderr)
        return 1
    write_history(history, args.out)
    print(f"{len(history)} days ({history[0]['date']} .. {history[-1]['date']}) -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
